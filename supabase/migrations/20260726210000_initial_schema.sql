create extension if not exists pgcrypto with schema extensions;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  display_name text not null default '',
  role text not null default 'member' check (role in ('admin', 'member')),
  membership_status text not null default 'inactive' check (membership_status in ('active', 'inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.site_settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

create table public.ebooks (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  subtitle text not null default '',
  description text not null default '',
  regular_price text not null default '',
  sale_price text not null default '',
  purchase_url text not null default '',
  cover_image text not null default '',
  sort_order integer not null default 0,
  is_published boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.member_resources (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('class', 'activity', 'audio', 'guide', 'resource')),
  month_label text not null default '',
  title text not null,
  description text not null default '',
  url text not null default '',
  sort_order integer not null default 0,
  is_published boolean not null default false,
  updated_at timestamptz not null default now()
);

create index ebooks_sort_idx on public.ebooks (sort_order, id);
create index resources_sort_idx on public.member_resources (sort_order, id);

