create policy "Users read their own profile"
on public.profiles for select to authenticated
using (id = (select auth.uid()));

create policy "Admins manage profiles"
on public.profiles for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy "Public reads settings"
on public.site_settings for select to anon, authenticated
using (true);

create policy "Admins manage settings"
on public.site_settings for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy "Public reads published ebooks"
on public.ebooks for select to anon, authenticated
using (is_published);

create policy "Admins manage ebooks"
on public.ebooks for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy "Active members read published resources"
on public.member_resources for select to authenticated
using (is_published and (select public.has_active_membership()));

create policy "Admins manage resources"
on public.member_resources for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

