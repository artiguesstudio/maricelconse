create or replace function public.is_configured_admin(candidate_email text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select encode(extensions.digest(lower(coalesce(candidate_email, '')), 'sha256'), 'hex') in (
    'd39fbb8efec67734e84ded9c9c8c3b5510444d10c19c00e82cf58f75bd17ce7a',
    '716e2f12c9e441a2cedea94e6c22d6746507b8c03e838f22d750738f0680e93c'
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, display_name, role, membership_status)
  values (
    new.id,
    lower(coalesce(new.email, '')),
    coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', ''),
    case when public.is_configured_admin(new.email) then 'admin' else 'member' end,
    case when public.is_configured_admin(new.email) then 'active' else 'inactive' end
  )
  on conflict (id) do update set
    email = excluded.email,
    display_name = case when excluded.display_name <> '' then excluded.display_name else public.profiles.display_name end,
    role = case when public.is_configured_admin(excluded.email) then 'admin' else public.profiles.role end,
    membership_status = case when public.is_configured_admin(excluded.email) then 'active' else public.profiles.membership_status end;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert or update of email, raw_user_meta_data on auth.users
for each row execute procedure public.handle_new_user();

insert into public.profiles (id, email, display_name, role, membership_status)
select
  id,
  lower(coalesce(email, '')),
  coalesce(raw_user_meta_data ->> 'full_name', raw_user_meta_data ->> 'name', ''),
  case when public.is_configured_admin(email) then 'admin' else 'member' end,
  case when public.is_configured_admin(email) then 'active' else 'inactive' end
from auth.users
on conflict (id) do update set
  email = excluded.email,
  role = case when public.is_configured_admin(excluded.email) then 'admin' else public.profiles.role end,
  membership_status = case when public.is_configured_admin(excluded.email) then 'active' else public.profiles.membership_status end;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

create or replace function public.has_active_membership()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid())
      and (role = 'admin' or membership_status = 'active')
  );
$$;

